def load_data(df):
    frame = df.copy()
    if "Index" not in frame.columns or "Y" not in frame.columns:
        raise ValueError("The labeled dataset must contain Index and Y columns.")
    frame.set_index("Index", inplace=True)
    return frame.drop(columns=["Y"]), frame[["Y"]]


def select_mcc_threshold(y, probability):
    values = np.unique(np.asarray(probability, dtype=float))
    candidates = np.r_[0.0, (values[:-1] + values[1:]) / 2, 1.0]
    scored = []
    for threshold in candidates:
        prediction = (probability >= threshold).astype(int)
        scored.append((
            matthews_corrcoef(y, prediction),
            balanced_accuracy_score(y, prediction),
            -abs(float(threshold) - 0.5),
            float(threshold),
        ))
    return max(scored)[-1]


def classification_metrics(y, probability, threshold):
    target = np.asarray(y).reshape(-1)
    probability = np.asarray(probability, dtype=float)
    prediction = (probability >= threshold).astype(int)
    metrics = _metrics_from_predictions(target, probability, prediction)
    metrics["threshold"] = float(threshold)
    return metrics


def _metrics_from_predictions(target, probability, prediction):
    tn, fp, fn, tp = confusion_matrix(target, prediction, labels=[0, 1]).ravel()
    return {
        "roc_auc": float(roc_auc_score(target, probability)),
        "average_precision": float(average_precision_score(target, probability)),
        "accuracy": float(accuracy_score(target, prediction)),
        "balanced_accuracy": float(balanced_accuracy_score(target, prediction)),
        "mcc": float(matthews_corrcoef(target, prediction)),
        "precision": float(precision_score(target, prediction, zero_division=0)),
        "recall": float(recall_score(target, prediction, zero_division=0)),
        "f1": float(f1_score(target, prediction, zero_division=0)),
        "sensitivity": float(tp / (tp + fn)) if tp + fn else math.nan,
        "specificity": float(tn / (tn + fp)) if tn + fp else math.nan,
        "tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp),
    }


def build_model_pipeline(model_name, best_parameters, n_features, seed):
    specs = model_specs(n_features, seed, [model_name])
    if not specs:
        raise ValueError(f"Unknown model family: {model_name}")
    pipeline = specs[0].estimator
    try:
        pipeline.set_params(**best_parameters)
    except ValueError as exc:
        raise ValueError(
            "The selected parameters are incompatible with the model pipeline. "
            "Use a best-by-model file generated by the new Params page."
        ) from exc
    return pipeline


def train_model_artifact(
    model_name,
    best_parameters,
    X,
    y,
    sample_ids=None,
    cv_folds=5,
    seed=20250725,
    workers=1,
):
    features = pd.DataFrame(X).copy()
    target = np.asarray(y).reshape(-1).astype(int)
    if len(features) != len(target):
        raise ValueError("Feature and target row counts do not match.")
    classes, counts = np.unique(target, return_counts=True)
    if len(classes) != 2:
        raise ValueError("Model training requires a binary target.")
    if counts.min() < cv_folds:
        raise ValueError(
            f"Each class needs at least {cv_folds} rows for {cv_folds}-fold CV."
        )
    if workers < 1:
        raise ValueError("Workers must be at least 1.")

    pipeline = build_model_pipeline(
        model_name, best_parameters, features.shape[1], seed
    )
    cv = StratifiedKFold(n_splits=cv_folds, shuffle=True, random_state=seed)
    probability = cross_val_predict(
        pipeline,
        features,
        target,
        cv=cv,
        method="predict_proba",
        n_jobs=workers,
        pre_dispatch=workers,
    )[:, 1]
    threshold = select_mcc_threshold(target, probability)
    prediction = (probability >= threshold).astype(int)
    metrics = classification_metrics(target, probability, threshold)
    pipeline.fit(features, target)

    identifiers = (
        np.asarray(sample_ids).reshape(-1).tolist()
        if sample_ids is not None
        else features.index.astype(str).tolist()
    )
    return {
        "artifact_version": 1,
        "model": pipeline,
        "model_name": model_name,
        "threshold": float(threshold),
        "feature_columns": features.columns.astype(str).tolist(),
        "label_column": "Y",
        "index_column": "Index",
        "seed": int(seed),
        "cv_folds": int(cv_folds),
        "best_parameters": best_parameters,
        "oof_metrics": metrics,
        "oof_probability": probability.tolist(),
        "oof_prediction": prediction.tolist(),
        "oof_target": target.tolist(),
        "sample_ids": identifiers,
        "evaluation": "development",
        "created_at": datetime.now().astimezone().isoformat(timespec="seconds"),
    }


def train_model_artifact_nested(
    model_name,
    X,
    y,
    sample_ids=None,
    outer_folds=5,
    inner_folds=5,
    search_trials=6,
    seed=20260725,
    workers=1,
    progress_callback=None,
):
    """Nested validation training.

    Each outer fold re-selects hyperparameters with an inner randomized search
    and picks the MCC threshold on the outer-training data only; pooled
    outer-test predictions give honest OOF metrics. A full-data search then
    refits the deployment model, whose threshold comes from the full-data
    inner OOF probabilities.
    """
    features, target = _validated_data(X, y, max(outer_folds, inner_folds))
    if search_trials < 1 or workers < 1:
        raise ValueError("Search trials and workers must be >= 1.")
    specs = model_specs(features.shape[1], seed, [model_name])
    if not specs:
        raise ValueError(f"Unknown model family: {model_name}")
    spec = specs[0]

    def plain_params(params):
        return {key: (value.item() if isinstance(value, np.generic) else value)
                for key, value in params.items()}

    def run_search(rows, labels):
        cv_splits = list(StratifiedKFold(n_splits=inner_folds, shuffle=True,
                                         random_state=seed).split(rows, labels))
        search = RandomizedSearchCV(
            clone(spec.estimator), spec.parameters, n_iter=search_trials,
            scoring=SCORING, refit="roc_auc", cv=cv_splits, random_state=seed,
            n_jobs=workers, pre_dispatch=workers, error_score=np.nan,
            return_train_score=False,
        )
        search.fit(rows, labels)
        if not np.isfinite(search.best_score_):
            raise RuntimeError(f"{model_name}: every candidate failed. Relax the search space or check the data.")
        return search, cv_splits

    n_samples = len(features)
    outer_probability = np.full(n_samples, np.nan)
    outer_prediction = np.full(n_samples, -1, dtype=int)
    fold_records = []
    outer_cv = StratifiedKFold(n_splits=outer_folds, shuffle=True, random_state=seed)
    for fold, (train, test) in enumerate(outer_cv.split(features, target), 1):
        rows, labels = features.iloc[train], target[train]
        search, inner_splits = run_search(rows, labels)
        best = clone(spec.estimator).set_params(**search.best_params_)
        inner_probability = cross_val_predict(
            best, rows, labels, cv=inner_splits, method="predict_proba",
            n_jobs=workers, pre_dispatch=workers)[:, 1]
        fold_threshold = select_mcc_threshold(labels, inner_probability)
        probability = search.best_estimator_.predict_proba(features.iloc[test])[:, 1]
        outer_probability[test] = probability
        outer_prediction[test] = (probability >= fold_threshold).astype(int)
        fold_records.append({
            "outer_fold": fold, "n_train": int(len(train)), "n_test": int(len(test)),
            "threshold": float(fold_threshold),
            "best_parameters": plain_params(search.best_params_),
            "best_inner_roc_auc": float(search.best_score_),
        })
        if progress_callback:
            progress_callback(fold, outer_folds, f"outer fold {fold}/{outer_folds}")
    if np.isnan(outer_probability).any() or (outer_prediction < 0).any():
        raise RuntimeError("Outer OOF did not cover every sample exactly once.")
    pooled_metrics = _metrics_from_predictions(target, outer_probability, outer_prediction)

    if progress_callback:
        progress_callback(0, outer_folds, "full-data selection")
    full_search, full_splits = run_search(features, target)
    full_best = clone(spec.estimator).set_params(**full_search.best_params_)
    full_probability = cross_val_predict(
        full_best, features, target, cv=full_splits, method="predict_proba",
        n_jobs=workers, pre_dispatch=workers)[:, 1]
    threshold = select_mcc_threshold(target, full_probability)
    fitted = full_search.best_estimator_

    identifiers = (
        np.asarray(sample_ids).reshape(-1).tolist()
        if sample_ids is not None
        else features.index.astype(str).tolist()
    )
    return {
        "artifact_version": 1,
        "model": fitted,
        "model_name": model_name,
        "threshold": float(threshold),
        "feature_columns": features.columns.astype(str).tolist(),
        "label_column": "Y",
        "index_column": "Index",
        "seed": int(seed),
        "cv_folds": int(outer_folds),
        "best_parameters": plain_params(full_search.best_params_),
        "oof_metrics": pooled_metrics,
        "oof_probability": outer_probability.tolist(),
        "oof_prediction": outer_prediction.tolist(),
        "oof_target": target.tolist(),
        "sample_ids": identifiers,
        "evaluation": "nested",
        "nested": {
            "outer_folds": int(outer_folds),
            "inner_folds": int(inner_folds),
            "search_trials": int(search_trials),
            "fold_thresholds": [record["threshold"] for record in fold_records],
            "outer_fold_detail": fold_records,
            "full_data_mean_inner_roc_auc": float(full_search.best_score_),
        },
        "source": "Nested validation, app-trained",
    }


def save_model_artifact(artifact, file_path):
    path = Path(file_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.suffix.lower() != ".joblib":
        path = path.with_suffix(".joblib")
    joblib.dump(artifact, path)
    return path


def _resolve_model_path(selected_file):
    path = Path(selected_file)
    if not path.is_absolute():
        path = MODEL_DIR / path
    return path


def _artifact_from_sidecar(pipeline, path):
    """Promote a bare pipeline to an artifact dict via an adjacent JSON sidecar.

    machine_learning_final stores model.joblib + model.json (threshold and
    metadata in the sidecar); importing such a pair gives the app the real
    threshold instead of silently falling back to 0.5.
    """
    sidecar = path.with_suffix(".json")
    if not sidecar.exists():
        return None
    try:
        meta = json.loads(sidecar.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if "threshold" not in meta:
        return None
    artifact = {
        "artifact_version": 1,
        "model": pipeline,
        "model_name": meta.get("family") or meta.get("model") or type(pipeline).__name__,
        "threshold": float(meta["threshold"]),
        "label_column": "Y",
        "index_column": "Index",
        "source": f"sidecar: {sidecar.name}",
    }
    if meta.get("input_columns"):
        artifact["feature_columns"] = list(meta["input_columns"])
    if "seed" in meta:
        artifact["seed"] = int(meta["seed"])
    if meta.get("threshold_selection"):
        artifact["threshold_selection"] = meta["threshold_selection"]
    return artifact


def load_model_artifact(selected_file, is_neural_network=False):
    path = _resolve_model_path(selected_file)
    suffix = path.suffix.lower()
    if suffix == ".joblib":
        loaded = joblib.load(path)
        if isinstance(loaded, dict) and "model" in loaded:
            return loaded
        promoted = _artifact_from_sidecar(loaded, path)
        if promoted is not None:
            return promoted
        return {"artifact_version": 0, "model": loaded, "model_name": type(loaded).__name__}
    if suffix == ".sav":
        with path.open("rb") as handle:
            model = pickle.load(handle)
        return {"artifact_version": 0, "model": model, "model_name": type(model).__name__}
    if suffix == ".h5" or is_neural_network:
        import tensorflow as tf
        model = tf.keras.models.load_model(path)
        return {"artifact_version": 0, "model": model, "model_name": "NeuralNetwork"}
    raise ValueError(f"Unsupported model file: {path.name}")


def feature_importance_table(artifact):
    model = artifact["model"]
    columns = np.asarray(artifact.get("feature_columns", []), dtype=object)
    if not hasattr(model, "named_steps") or not len(columns):
        return pd.DataFrame(columns=["feature", "importance"])
    if "variance" in model.named_steps:
        columns = columns[model.named_steps["variance"].get_support()]
    if "select" in model.named_steps:
        columns = columns[model.named_steps["select"].get_support()]
    estimator = model.named_steps.get("model")
    if hasattr(estimator, "feature_importances_"):
        importance = np.asarray(estimator.feature_importances_, dtype=float)
    elif hasattr(estimator, "coef_"):
        coefficients = np.asarray(estimator.coef_, dtype=float)
        importance = np.abs(coefficients).mean(axis=0) if coefficients.ndim > 1 else np.abs(coefficients)
    else:
        return pd.DataFrame(columns=["feature", "importance"])
    if len(columns) != len(importance):
        return pd.DataFrame(columns=["feature", "importance"])
    return pd.DataFrame(
        {"feature": columns, "importance": importance}
    ).sort_values("importance", ascending=False, ignore_index=True)


def evaluate_artifact_on_data(artifact, X, y):
    model = artifact["model"]
    features = pd.DataFrame(X).loc[:, artifact.get("feature_columns", list(X.columns))]
    target = np.asarray(y).reshape(-1)
    probability = model.predict_proba(features)[:, 1]
    threshold = float(artifact.get("threshold", 0.5))
    return classification_metrics(target, probability, threshold), probability
